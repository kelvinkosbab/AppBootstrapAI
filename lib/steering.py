#!/usr/bin/env python3
"""AppBootstrapAI installer — AI steering-file checks for `audit`.

Finds a target repo's agent instruction files (CLAUDE.md, AGENTS.md, GEMINI.md,
Copilot / Cursor / Kiro rules, .claude rules, skills, subagents, commands,
settings) and flags the problems .claude/rules/ai-steering-files.md describes:
stale paths and commands, unfilled placeholders, oversized always-loaded files,
copies drifting across agents, advice that contradicts the bundle's rules,
missing scope frontmatter, over-broad permissions, and secrets.

Like the code checks in audit.py these are cheap heuristics that say where to
look. Files the bundle installed are skipped: the bundle owns their content.

audit.py calls run(); it returns (findings, summary) as plain data.
"""

from __future__ import annotations

import glob
import json
import os
import re
import subprocess

RULE = "ai-steering-files.md"
MAX_ALWAYS_LINES = 300
MAX_ALWAYS_BYTES = 25_000
MAX_READ_BYTES = 1_000_000
MAX_DEPTH = 4
SKIP_DIRS = {".git", ".build", "build", ".gradle", "DerivedData", "Pods", "Carthage",
             "node_modules", ".swiftpm", ".idea", "xcuserdata", ".cxx", "captures"}

# Manifest entry types the user is expected to edit after install.
PROJECT_OWNED_TYPES = {"template", "settings"}
GENERATED_MARKER = "Generated by AppBootstrapAI"
SKILL_FIX = "Add `name:` and a `description:` that says when to use it."
SCOPE_FIX = ("Add scope frontmatter: `globs:` (or `paths:`) on .claude/rules, `globs:` / `alwaysApply:` / "
             "`description:` on Cursor .mdc, `applyTo:` on Copilot .instructions.md.")
ROOT_FILES = ("CLAUDE.md", "AGENTS.md", "GEMINI.md", ".github/copilot-instructions.md")

NEGATION = re.compile(r"\b(never|avoid|don'?t|do not|no longer|not|instead|replace[sd]?|"
                      r"ban(?:ned)?|forbid(?:den)?|deprecated|stop|remove|migrate|prefer|over|rather than|legacy)\b", re.I)

# Advice that the bundle's rules forbid, when written without a negation.
CONFLICTS = [
    ("apple", re.compile(r"DispatchQueue\.main\.async"), "apple-swift6-strict-concurrency.md"),
    ("apple", re.compile(r"@unchecked\s+Sendable"), "apple-swift6-strict-concurrency.md"),
    ("apple", re.compile(r"\btry!"), "apple-swift6-strict-concurrency.md"),
    ("apple", re.compile(r"UIScreen\.main\b"), "apple-adaptive-layout.md"),
    ("apple", re.compile(r"\.system\(size:"), "apple-accessibility-best-practices.md"),
    ("android", re.compile(r"\bGlobalScope\b"), "android-coroutines-best-practices.md"),
    ("android", re.compile(r"\bLiveData\b"), "android-coroutines-best-practices.md"),
    ("android", re.compile(r"\.collectAsState\(\)"), "android-compose-best-practices.md"),
    ("android", re.compile(r"\bkapt\b"), "android-gradle-conventions.md"),
    ("android", re.compile(r"android\.util\.Log\b|\bLog\.[vdiwe]\("), "android-logging-strategy.md"),
    ("android", re.compile(r"material-icons-extended"), "android-iconography.md"),
    ("android", re.compile(r"announceForAccessibility"), "android-accessibility-best-practices.md"),
]

VAGUE = re.compile(r"follow (?:the |all |our )?(?:best|good) practices|\bclean code\b|"
                   r"write (?:good|clean|high[- ]quality|maintainable|readable|efficient) code|"
                   r"\bbe careful\b|use common sense|keep (?:it|the code) (?:simple|clean)\b", re.I)

PLACEHOLDER = re.compile(r"<[A-Z][A-Z0-9_]{3,}>")
COMMAND_HINT = re.compile(r"\./gradlew|\bgradle\b|xcodebuild|\bswift (?:build|test)\b|"
                          r"\b(?:npm|pnpm|yarn) (?:run|test)\b|\bmake\b|\bfastlane\b|"
                          r"\bbundle exec\b|\bpytest\b|\bcargo\b|\btuist\b")
INLINE_PATH = re.compile(r"`([A-Za-z0-9_.@-][A-Za-z0-9_.@/-]*/[A-Za-z0-9_.@/-]*)`")
MD_LINK = re.compile(r"\]\(([^)\s#]+)(?:#[^)]*)?\)")
# Files that exist only after a tool or a developer creates them; mentioning one isn't stale.
CREATED_LATER = {"settings.local.json", "CLAUDE.local.md", ".appbootstrap-manifest.json",
                 "appbootstrap-audit-baseline.json", "local.properties", ".env"}
# A path mentioned as something to create, not something that exists.
CREATION_WORDS = re.compile(r"\b(goes? (?:in|to|into)|write|writes|written|creates?|generates?|add|adds|"
                            r"git-?ignored?|output|lands? in|e\.g\.|for example|such as|like)\b", re.I)
SCRIPT_CALL = re.compile(r"(?<![\w/.])\./((?:[\w.-]+/)*[\w.-]+\.(?:sh|py|rb|js|mjs))\b")
NPM_RUN = re.compile(r"\b(?:npm|pnpm|yarn) run ([\w:.-]+)")
MAKE_TARGET = re.compile(r"(?:^|[`$\s])make ([a-z][\w-]*)\b")
FASTLANE = re.compile(r"\bfastlane (?:\w+ )?(\w+)\b")
SWIFT_CMD = re.compile(r"\bswift (?:build|test)\b(?:[^\n`]*?--package-path[ =](\S+))?")


def _walk(target):
    """Yield (rel_path, abs_path) for files at most MAX_DEPTH dirs deep."""
    for root, dirs, files in os.walk(target):
        rel_root = os.path.relpath(root, target)
        depth = 0 if rel_root == "." else rel_root.count(os.sep) + 1
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.endswith((".xcodeproj", ".xcworkspace"))]
        if depth >= MAX_DEPTH:
            dirs[:] = []
        for fn in files:
            path = os.path.join(root, fn)
            yield os.path.relpath(path, target).replace(os.sep, "/"), path


def _classify(rel):
    """Return (agent, kind) for a steering file, or None. kind: always|directory|scoped|on-demand|config."""
    base = os.path.basename(rel)
    top = "/" not in rel
    if base == "CLAUDE.md":
        return ("claude", "always" if top else "directory")
    if base == "CLAUDE.local.md":
        return ("claude", "always")
    if base == "AGENTS.md":
        return ("agents-md", "always" if top else "directory")
    if base == "GEMINI.md":
        return ("gemini", "always" if top else "directory")
    if rel == ".github/copilot-instructions.md":
        return ("copilot", "always")
    if rel.startswith(".github/instructions/") and rel.endswith(".instructions.md"):
        return ("copilot", "scoped")
    if rel == ".cursorrules":
        return ("cursor", "always")
    if rel == ".windsurfrules":
        return ("windsurf", "always")
    if rel.startswith(".cursor/rules/") and rel.endswith((".mdc", ".md")):
        return ("cursor", "scoped")
    if rel.startswith(".kiro/steering/") and rel.endswith(".md"):
        return ("kiro", "scoped")
    if rel.startswith(".claude/rules/") and rel.endswith(".md"):
        return ("claude", "scoped")
    if re.match(r"\.claude/skills/[^/]+/SKILL\.md$", rel):
        return ("claude", "on-demand")
    if rel.startswith((".claude/agents/", ".claude/commands/")) and rel.endswith(".md"):
        return ("claude", "on-demand")
    if rel == ".claude/settings.json":
        return ("claude", "config")
    return None


def _frontmatter(text):
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end < 0:
        return None
    fm = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip().strip("\"'")
    return fm


def _read(path):
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as fh:
            return fh.read(MAX_READ_BYTES)
    except OSError:
        return ""


def _bundle_names(bundle):
    rules = {os.path.splitext(os.path.basename(p))[0]
             for p in glob.glob(os.path.join(bundle, ".claude", "rules", "*.md"))}
    skills = {os.path.basename(os.path.dirname(p))
              for p in glob.glob(os.path.join(bundle, ".claude", "skills", "*", "SKILL.md"))}
    return rules, skills


def _owner(rel, text, manifest_types, bundle_rules, bundle_skills):
    if rel in manifest_types:
        return "project" if manifest_types[rel] in PROJECT_OWNED_TYPES else "bundle"
    if GENERATED_MARKER in text[:300]:
        return "bundle"
    stem = os.path.splitext(os.path.basename(rel))[0]
    if rel.startswith((".claude/rules/", ".cursor/rules/", ".kiro/steering/")) and stem in bundle_rules:
        return "bundle"
    m = re.match(r"\.claude/skills/([^/]+)/", rel)
    if m and m.group(1) in bundle_skills:
        return "bundle"
    if "appbootstrap-sync" in rel:
        return "bundle"
    return "project"


def _strip_fences(text):
    """Return the lines outside fenced code blocks as (lineno, line) pairs."""
    out, fenced = [], False
    for n, line in enumerate(text.splitlines(), 1):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if not fenced:
            out.append((n, line))
    return out


def _find_file(target, name, depth=2):
    for rel, _ in _walk(target):
        if os.path.basename(rel) == name and rel.count("/") <= depth:
            return True
    return False


def _norm_lines(text):
    return {re.sub(r"\s+", " ", ln.strip().lower()) for ln in text.splitlines()
            if len(ln.strip()) > 20 and not ln.strip().startswith(("```", "---", "|-"))}


def _ignored(target, rel):
    try:
        r = subprocess.run(["git", "-C", target, "check-ignore", "-q", rel],
                           capture_output=True, timeout=10)
        if r.returncode in (0, 1):
            return r.returncode == 0
    except (OSError, subprocess.SubprocessError):
        pass
    gi = _read(os.path.join(target, ".gitignore"))
    return os.path.basename(rel) in gi


def run(target, bundle, platforms, manifest_files, secret_pattern):
    """Return (findings, summary). Each finding: {id, title, severity, fix, rule, locations[]}."""
    manifest_types = {e.get("path", ""): e.get("type", "") for e in manifest_files}
    bundle_rules, bundle_skills = _bundle_names(bundle)
    findings: dict = {}

    def add(id_, title, sev, fix, loc, rule=RULE):
        f = findings.setdefault(id_, {"id": id_, "title": title, "severity": sev,
                                      "fix": fix, "rule": rule, "locations": []})
        f["locations"].append(loc)

    files, conflicts = [], []
    for rel, path in _walk(target):
        cls = _classify(rel)
        if not cls:
            continue
        text = _read(path)
        agent, kind = cls
        entry = {"path": rel, "agent": agent, "kind": kind,
                 "lines": text.count("\n") + (1 if text and not text.endswith("\n") else 0),
                 "bytes": len(text.encode("utf-8")),
                 "owner": _owner(rel, text, manifest_types, bundle_rules, bundle_skills)}
        fm = _frontmatter(text)
        # A scoped file without scope frontmatter is effectively always loaded.
        if kind == "scoped" and agent == "claude" and not (fm and (fm.get("globs") or fm.get("paths"))):
            entry["kind"] = "always"
        if agent == "cursor" and rel != ".cursorrules":
            if fm and fm.get("alwaysApply", "").lower() == "true":
                entry["kind"] = "always"
            elif not (fm and fm.get("globs")):
                entry["kind"] = "on-demand" if fm and fm.get("description") else "manual"
        if agent == "kiro":
            inclusion = (fm or {}).get("inclusion", "always")
            entry["kind"] = {"always": "always", "manual": "manual"}.get(inclusion, "scoped")
        files.append((entry, text, fm))

    project = [(e, t, fm) for e, t, fm in files if e["owner"] == "project"]

    for e, text, fm in project:
        rel = e["path"]
        if e["kind"] == "config":
            _check_settings(rel, text, add)
            continue
        for n, line in enumerate(text.splitlines(), 1):
            if secret_pattern.search(line):
                add("steering-secret", "API key or token in an AI steering file", "high",
                    "Remove it, rotate the key, and name the secret and where it lives instead.",
                    f"{rel}:{n}")
        prose = _strip_fences(text)
        for n, line in prose:
            if PLACEHOLDER.search(re.sub(r"`[^`]*`", "", line)):
                add("steering-placeholder", "Unfilled template placeholder in a steering file", "medium",
                    "Fill in or delete placeholders like <PROJECT_NAME>; agents treat them as facts.",
                    f"{rel}:{n}")
            if VAGUE.search(line):
                add("steering-vague", "Generic advice an agent can't act on", "low",
                    "Replace it with the concrete rule (what to do, where) or delete it.", f"{rel}:{n}")
        _check_conflicts(rel, text, platforms, add, conflicts)
        _check_paths(target, rel, prose, add)
        _check_commands(target, rel, text, add)
        _check_frontmatter(e, fm, add)
        if e["kind"] == "always" and (e["lines"] > MAX_ALWAYS_LINES or e["bytes"] > MAX_ALWAYS_BYTES):
            add("steering-oversized", f"Always-loaded steering file over {MAX_ALWAYS_LINES} lines", "medium",
                "Keep the root file to commands, map, and gotchas; move topic guidance into scoped rules.",
                rel)
        if rel == ".cursorrules":
            add("steering-legacy-format", "Legacy `.cursorrules` file", "low",
                "Move it into scoped .cursor/rules/*.mdc files and delete .cursorrules.", rel)
        if os.path.basename(rel) == "CLAUDE.local.md" and not _ignored(target, rel):
            add("steering-local-committed", "Personal steering file isn't git-ignored", "low",
                "Add CLAUDE.local.md and .claude/settings.local.json to .gitignore.", rel)

    if os.path.isfile(os.path.join(target, ".claude", "settings.local.json")) \
            and not _ignored(target, ".claude/settings.local.json"):
        add("steering-local-committed", "Personal steering file isn't git-ignored", "low",
            "Add CLAUDE.local.md and .claude/settings.local.json to .gitignore.",
            ".claude/settings.local.json")

    overlaps = _check_duplicates(project, add)

    roots = [e for e, _, _ in project if e["path"] in ROOT_FILES]
    if roots and not any(COMMAND_HINT.search(t) for e, t, _ in project if e in roots):
        add("steering-no-commands", "Steering files don't say how to build or test", "low",
            "Add the exact build, test, and lint commands for this repo to the root steering file.",
            roots[0]["path"])

    instruction_files = [e for e, _, _ in files if e["kind"] != "config"]
    if not instruction_files:
        add("steering-none", "No AI steering files", "low",
            "Add a CLAUDE.md or AGENTS.md with build/test commands, the module map, and gotchas "
            "(install.sh writes a starter).", "(repo root)")

    # Each agent reads only its own files, so context cost is per agent.
    per_agent: dict = {}
    for e, _, _ in files:
        if e["kind"] == "always":
            per_agent[e["agent"]] = per_agent.get(e["agent"], 0) + e["bytes"] // 4
    summary = {
        "rule_path": os.path.join(bundle, ".claude", "rules", RULE),
        "files": [e for e, _, _ in files],
        "agents": sorted({e["agent"] for e, _, _ in files if e["kind"] != "config"}),
        "always_loaded_tokens_est": per_agent,
        "project_files": len([e for e in project if e[0]["kind"] != "config"]),
        "bundle_files": len([e for e, _, _ in files if e["owner"] == "bundle"]),
        "overlaps": overlaps,
        "conflicts": conflicts,
    }
    return list(findings.values()), summary


def _check_conflicts(rel, text, platforms, add, details):
    for n, line in enumerate(text.splitlines(), 1):
        if NEGATION.search(line):
            continue
        for plat, pattern, rule in CONFLICTS:
            if platforms and plat not in platforms:
                continue
            if pattern.search(line):
                add("steering-contradicts-bundle", "Steering advice contradicts a bundle rule", "medium",
                    "Align it with the rule named in steering.conflicts, or mark it as a deliberate "
                    "project exception with the reason.", f"{rel}:{n}")
                details.append({"location": f"{rel}:{n}", "match": pattern.pattern, "rule": rule})
                break


def _check_paths(target, rel, prose, add):
    here = os.path.dirname(os.path.join(target, rel))
    for n, line in prose:
        if CREATION_WORDS.search(line):
            continue
        candidates = INLINE_PATH.findall(line) + [m for m in MD_LINK.findall(line)
                                                   if not re.match(r"^[a-z][\w+.-]*:", m)]
        for tok in candidates:
            tok = re.sub(r":\d+(?:-\d+)?$", "", tok).rstrip("/")
            if not tok or tok.startswith(("/", "~", "http")) or any(c in tok for c in "*<>{}$") \
                    or os.path.basename(tok) in CREATED_LATER:
                continue
            first = tok.split("/")[0]
            in_root = os.path.exists(os.path.join(target, tok))
            in_here = os.path.exists(os.path.normpath(os.path.join(here, tok)))
            # Only a path whose first segment exists is clearly about this repo.
            anchored = first in ("..", ".") or os.path.exists(os.path.join(target, first)) \
                or os.path.exists(os.path.join(here, first))
            if anchored and not in_root and not in_here:
                add("steering-stale-path", "Steering file references a path that doesn't exist", "medium",
                    "Update the path to where the file lives now, or delete the instruction.",
                    f"{rel}:{n}")


def _check_commands(target, rel, text, add):
    has_gradlew = os.path.isfile(os.path.join(target, "gradlew")) or _find_file(target, "gradlew")
    has_package = None
    pkg_scripts = None
    for n, line in enumerate(text.splitlines(), 1):
        if "<" in line and ">" in line:
            continue
        stale = None
        if "./gradlew" in line and not has_gradlew:
            stale = "./gradlew"
        m = SWIFT_CMD.search(line)
        if not stale and m:
            if m.group(1):
                if not os.path.isfile(os.path.join(target, m.group(1).strip("`'\""), "Package.swift")):
                    stale = "swift --package-path"
            else:
                if has_package is None:
                    has_package = _find_file(target, "Package.swift", depth=2)
                if not has_package:
                    stale = "swift build/test"
        for script in SCRIPT_CALL.findall(line):
            if not stale and not os.path.isfile(os.path.join(target, script)):
                stale = script
        m = NPM_RUN.search(line)
        if not stale and m:
            if pkg_scripts is None:
                try:
                    with open(os.path.join(target, "package.json")) as fh:
                        pkg_scripts = set(json.load(fh).get("scripts", {}))
                except (OSError, ValueError):
                    pkg_scripts = set()
            if m.group(1) not in pkg_scripts:
                stale = m.group(0)
        m = MAKE_TARGET.search(line)
        if not stale and m and not os.path.isfile(os.path.join(target, "Makefile")):
            stale = "make"
        if not stale and FASTLANE.search(line) and not (
                os.path.isfile(os.path.join(target, "fastlane", "Fastfile")) or _find_file(target, "Fastfile", 3)):
            stale = "fastlane"
        if stale:
            add("steering-stale-command", "Steering file gives a command this repo can't run", "medium",
                "Replace it with the command that works today (and keep it in sync with the build).",
                f"{rel}:{n}")


def _check_frontmatter(e, fm, add):
    rel, agent = e["path"], e["agent"]
    fm = fm or {}
    if re.match(r"\.claude/skills/[^/]+/SKILL\.md$", rel) and not (fm.get("name") and fm.get("description")):
        add("steering-skill-frontmatter", "Skill or subagent has no name/description, so it never triggers", "medium",
            SKILL_FIX, rel)
    elif rel.startswith(".claude/agents/") and not fm.get("description"):
        add("steering-skill-frontmatter", "Skill or subagent has no name/description, so it never triggers", "medium",
            SKILL_FIX, rel)
    elif rel.startswith(".claude/rules/") and e["kind"] == "always":
        add("steering-unscoped-rule", "Rule file has no scope, so it loads on every request", "low",
            SCOPE_FIX,
            rel)
    elif agent == "cursor" and rel != ".cursorrules" and e["kind"] == "manual":
        add("steering-unscoped-rule", "Cursor rule has no description or globs, so it applies only when @-mentioned", "low",
            SCOPE_FIX, rel)
    elif rel.startswith(".github/instructions/") and not fm.get("applyTo"):
        add("steering-unscoped-rule", "Rule file has no scope, so it loads on every request", "low",
            SCOPE_FIX, rel)


def _check_settings(rel, text, add):
    try:
        data = json.loads(text)
    except ValueError:
        return
    perms = data.get("permissions") or {}
    allow = perms.get("allow") or []
    broad = {"Bash", "Bash(*)", "Bash(:*)", "*"}
    if any(a in broad for a in allow if isinstance(a, str)) or perms.get("defaultMode") == "bypassPermissions":
        add("steering-permissive-settings", "Shared agent settings allow any shell command", "medium",
            "Allow specific commands (`Bash(./gradlew:*)`); keep broad grants in git-ignored "
            "settings.local.json.", rel)


def _check_duplicates(project, add):
    docs = [(e["path"], _norm_lines(t)) for e, t, _ in project
            if e["kind"] in ("always", "directory")]
    overlaps = []
    for i, (a, la) in enumerate(docs):
        for b, lb in docs[i + 1:]:
            shared = la & lb
            smaller = min(len(la), len(lb))
            if smaller and len(shared) >= 10 and len(shared) / smaller >= 0.5:
                overlaps.append({"files": [a, b], "shared_lines": len(shared),
                                 "share": round(len(shared) / smaller, 2)})
                add("steering-duplicated", "Same instructions copied across agent files", "medium",
                    "Keep one source (e.g. AGENTS.md, imported from CLAUDE.md with @AGENTS.md) and "
                    "derive the others, or generate them with install.sh --agents / a sync tool.", b)
    return overlaps
